iw, ib = hdr.index("WBS"), hdr.index("실제구현내용")

seen, changed = set(), 0
for r in rows[1:]:
    if len(r) <= ib:
        continue
    w = r[iw]
    if w in B:
        assert w not in seen, f"WBS 중복: {w}"
        seen.add(w)
        new = B[w]
        assert "\t" not in new and "\n" not in new, w
        if r[ib] != new:
            r[ib] = new
            changed += 1

missing = sorted(set(B) - seen)
assert not missing, f"파일에 없는 WBS: {missing}"

with io.open(P, "w", encoding="utf-8", newline="\n") as f:
    for r in rows:
        f.write("\t".join(r) + "\n")

